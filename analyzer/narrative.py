"""
叙事结构分析 — 情节结构、节奏曲线、叙事线索
"""
from analyzer.llm import NovelLLM

NARRATIVE_PROMPT = """你是一位专业叙事学研究者。请分析以下小说的叙事结构。

请从以下维度分析：

1. **结构类型**：线性叙事/倒叙/插叙/多线并行/环状结构？请指出依据
2. **情节点分析**：
   - 开端/引入：故事如何开始？
   - 发展/上升：冲突如何升级？
   - 高潮/转折：最关键的转折点是什么？
   - 结局/收束：故事如何结束？
3. **叙事节奏曲线**：用文字描述故事的张力变化曲线（平淡→紧张→高潮→释放）
4. **时间线**：是否存在时间跳跃？回忆/预叙的使用
5. **叙事线索**：主线/支线，明线/暗线的设置
6. **结构评分**：给叙事结构一个综合评分(1-10)

请用 Markdown 格式输出。"""


def analyze_narrative(text: str, model: str = "claude") -> str:
    """分析叙事结构"""
    llm = NovelLLM(model)
    # 叙事分析需要更多上下文，取前12000字
    sample = text[:12000]
    return llm.invoke(NARRATIVE_PROMPT, f"请分析以下小说的叙事结构：\n\n{sample}")
