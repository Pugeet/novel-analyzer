"""
写作风格分析 — 叙事视角、语言节奏、修辞手法、词汇特征
"""
from analyzer.llm import NovelLLM

STYLE_PROMPT = """你是一位专业文学评论家。请对以下小说片段进行写作风格分析。

请从以下维度分析（每个维度2-3句话）：

1. **叙事视角**：第一人称/第三人称/上帝视角？视角是否稳定？
2. **语言节奏**：句式长短变化、段落节奏、是否使用短句营造紧张感或长句铺陈？
3. **修辞手法**：比喻、排比、反复、对比等手法使用频率和效果
4. **词汇特征**：书面语/口语化、成语使用、地域方言、时代感
5. **整体风格**：简约/华丽、冷静/激情、幽默/严肃、诗意/白描
6. **风格评分**：给写作风格一个综合评分(1-10)并说明理由

请用 Markdown 格式输出，直接给出分析结果，不要额外开场白。"""


def analyze_style(text: str, model: str = "claude") -> str:
    """分析写作风格"""
    llm = NovelLLM(model)
    # 取前6000字分析（兼顾上下文和成本）
    sample = text[:6000]
    return llm.invoke(STYLE_PROMPT, f"请分析以下小说的写作风格：\n\n{sample}")
