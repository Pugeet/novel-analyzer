"""
冲突与高潮分析 — 冲突类型、张力、高潮设置
"""
from analyzer.llm import NovelLLM

CONFLICT_PROMPT = """你是一位专业文学编辑，擅长分析小说的冲突设计和高潮设置。

请从以下维度分析：

1. **核心冲突**：用一句话概括小说的核心冲突（人vs人/人vs社会/人vs自然/人vs自我）
2. **冲突层次**：
   - 外部冲突：人物之间的矛盾、利益冲突、对抗关系
   - 内部冲突：主角的内心矛盾、成长障碍、道德困境
3. **冲突升级**：冲突如何逐步升级？关键转折事件是什么？
4. **高潮分析**：
   - 高潮位置：高潮出现在什么位置？是否合理？
   - 高潮力度：高潮段落的情感冲击力和戏剧张力
   - 高潮类型：动作型/情感型/智斗型/反转型
5. **张力维持**：作者如何在非高潮段落维持读者的阅读兴趣？
6. **冲突评分**：给冲突设计一个综合评分(1-10)

请用 Markdown 格式输出。"""


def analyze_conflict(text: str, model: str = "claude") -> str:
    """分析冲突与高潮"""
    llm = NovelLLM(model)
    sample = text[:10000]
    return llm.invoke(CONFLICT_PROMPT, f"请分析以下小说的冲突与高潮：\n\n{sample}")
